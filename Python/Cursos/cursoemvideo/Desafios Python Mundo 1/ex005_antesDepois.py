#Crie um programa que peça um numero ao usuário e mostre na tela:
#O numero digitado, seu antecessor e seu sucessor.

numero = int(input('Digite um numero: '))
antecessor = numero - 1
sucessor = numero + 1
print(f'Analisando o valor {numero}, seu antecessor é {antecessor} e o sucessor é {sucessor}')




